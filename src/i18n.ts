function composeEn(text: string): string | null {
  let rest = text;
  let verb: string | null = null;
  for (const [re, en] of EN_VERBS) {
    if (re.test(rest)) { verb = en; rest = rest.slice(rest.match(re)![0].length); break; }
  }
  if (!verb) return null;
  let noun = '';
  for (const [re, en] of EN_NOUNS) {
    const m = rest.match(re);
    if (m) { noun = en; rest = rest.slice(m[0].length); break; }
  }
  if (!noun) return null;
  const tail = rest.trim();
  if (tail && !/^[：:，,（(）)。.、;；0-9A-Za-z_\-\s]*$/.test(tail)) return null;
  return verb.charAt(0).toUpperCase() + verb.slice(1) + ' ' + noun;
}

export function translateError(text: string): string {
  const hit = bySource[text];
  if (hit) return hit[current === 'zh-CN' ? 'zh' : current === 'zh-TW' ? 'tw' : 'en'];
  if (current === 'zh-CN') return text;
  if (current === 'zh-TW') return s2t(text);
  return rustEnTranslate(text) ?? composeEn(text) ?? text;
}

export function trError(error: unknown, fallback?: string): string {
  if (typeof error === 'string' && error.length <= 200) return translateError(error);
  return fallback ?? 'Operation failed; check your network and retry';
}

// Sync the language to the Rust side (tray menu texts) — best effort.
export function syncLangToBackend(lang: Lang): void {
  if (!(window as unknown as { __TAURI_INTERNALS__?: unknown }).__TAURI_INTERNALS__) return;
  void import('@tauri-apps/api/core').then(({ invoke }) =>
    invoke('v1_set_language', { lang }).catch(() => undefined));
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const entry = dict[key] ?? bySource[key];
  let text = entry ? entry[current === 'zh-CN' ? 'zh' : current === 'zh-TW' ? 'tw' : 'en'] : key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
  }
  return text;
}
