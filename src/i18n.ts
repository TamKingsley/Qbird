// Lightweight i18n for Qbird. Phase 1 covers the app frame: navigation,
// settings tabs/general page, onboarding, close prompt and about page.
// Chat surfaces and Rust backend errors remain Chinese for now (see PRD 3.10.1).

export type Lang = 'zh-CN' | 'zh-TW' | 'en';

const LANG_KEY = 'qbird.lang';
const LANGS: Lang[] = ['zh-CN', 'zh-TW', 'en'];

export const LANG_LABEL: Record<Lang, string> = {
  'zh-CN': '简体中文',
  'zh-TW': '繁體中文',
  en: 'English',
};

let current: Lang = detectLang();

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && (LANGS as string[]).includes(saved)) return saved as Lang;
  } catch { /* storage unavailable */ }
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : '';
  if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk') || nav.startsWith('zh-hant')) return 'zh-TW';
  if (nav.startsWith('en')) return 'en';
  return 'zh-CN';
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* storage unavailable */ }
}

